class CampusMenuCoverageTests(unittest.TestCase):
    def test_every_menu_dish_is_made_of_known_ingredients(self):
        self.assertGreaterEqual(len(DISHES), 180)  # many entries group several dishes of one kind
        for dish, (components, method) in DISHES.items():
            self.assertIn(method, COOKING_METHODS, dish)
            self.assertEqual(sum(share for _, share in components), 100, dish)
            unknown = [key for key, _ in components if key not in INGREDIENTS]
            self.assertEqual(unknown, [], dish)
            nutrition = food_nutrition(components, method)
            self.assertEqual(nutrition['known_share'], D('1.00'), dish)
            total = nutrition['visible_kcal_per_100g'] + nutrition['hidden_kcal_per_100g'][1]
            self.assertTrue(0 <= total < 700, (dish, total))


